def generate():
    assert len(MAP) == 12 and all(len(row) == 12 for row in MAP)
    assert all(c == '#' for c in MAP[0] + MAP[-1])
    assert all(row[0] == row[-1] == '#' for row in MAP)
    table = [0] * (100 * 7)
    for character, rows in FONT.items():
        code = ord(character)-ord('A')+10 if character.isalpha() else ord(character)-ord('0')+36
        for y, row in enumerate(rows):
            table[code*7+y] = sum((1 if bit == '1' else -1) * 3**(5-x) for x, bit in enumerate(row+'0'))
    for code in range(100):
        if not (10 <= code <= 45):
            table[code*7:code*7+7] = [-364]*7
    symbols = {'#':1, '.':0, 'C':2, 'A':3, 'X':4}
    arrays = {
        'level': [symbols[c] for row in MAP for c in row],
        'cosine': [round(81*math.cos(i*math.pi/18)) for i in range(36)],
        'font': table,
    }
    return '// Generated original Ternary Breach assets. GPL-2.0-or-later.\n' + '\n'.join(
        'char '+name+'['+str(len(values))+'] = {'+','.join(map(str, values))+'};' for name, values in arrays.items())+'\n'

if __name__ == '__main__':
    Path(sys.argv[1]).write_text(generate())
